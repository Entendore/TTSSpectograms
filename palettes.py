import os
import numpy as np
import cv2
from typing import Dict, Optional, List, Tuple
from PySide6.QtCore import QStandardPaths

PALETTE_FOLDER = "palettes"


def get_default_palette_dir() -> str:
    config_dir = QStandardPaths.writableLocation(QStandardPaths.AppDataLocation)
    palette_dir = os.path.join(config_dir, PALETTE_FOLDER)
    return palette_dir


def _lerp(a: int, b: int, t: float) -> int:
    return int(a + (b - a) * t)


def _generate_gradient(stops: List[Tuple[float, int, int, int]], n: int = 256) -> List[Tuple[int, int, int]]:
    colors = []
    for i in range(n):
        t = i / (n - 1) if n > 1 else 0.0
        matched = False
        for j in range(len(stops) - 1):
            if stops[j][0] <= t <= stops[j + 1][0]:
                span = stops[j + 1][0] - stops[j][0]
                t_local = (t - stops[j][0]) / span if span > 0 else 0.0
                r = _lerp(stops[j][1], stops[j + 1][1], t_local)
                g = _lerp(stops[j][2], stops[j + 1][2], t_local)
                b = _lerp(stops[j][3], stops[j + 1][3], t_local)
                colors.append((max(0, min(255, r)), max(0, min(255, g)), max(0, min(255, b))))
                matched = True
                break
        if not matched:
            colors.append((stops[-1][1], stops[-1][2], stops[-1][3]))
    return colors


